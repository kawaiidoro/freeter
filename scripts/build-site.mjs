// Dependency-free packaging. site.js is committed, so visitors never need a build.
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const core = (await readFile(new URL('core.js', root), 'utf8')).replace(/^export /gm, '');
const app = (await readFile(new URL('app.js', root), 'utf8')).replace(/^import .*?;\r?\n/, '');
const output = `/* Generated by node scripts/build-site.mjs. Edit core.js and app.js. */\n(() => {\n'use strict';\n${core}\n${app}\n})();\n`;
const file = new URL('site.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(file, 'utf8') !== output) throw new Error('site.js is stale. Run node scripts/build-site.mjs.');
  console.log('site.js matches source files.');
} else {
  await writeFile(file, output);
  console.log('Generated site.js (no external dependencies).');
}
