// Reproducible, self-contained runtime; every shell references the same release.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(name, root), 'utf8');
const names = ['core.js','app.js','vendor/quill.js','style.css','brand.css','vendor/quill.core.css','scripts/sw-template.js'];
const values = await Promise.all(names.map(read));
const source = Object.fromEntries(names.map((name,index)=>[name,values[index]]));
const release = createHash('sha256').update(values.join('\0')).digest('hex').slice(0,12);
const core = source['core.js'].replace(/^export /gm, '');
const app = source['app.js'].replace(/^import .*?;\r?\n/, '').replaceAll('__FREETER_RELEASE__',release);
const runtime = `/* Generated by scripts/build-site.mjs. Includes Quill 2.0.3 (BSD-3-Clause); see vendor/QUILL-LICENSE.txt. */\n(() => {\n'use strict';\n${source['vendor/quill.js']}\n${core}\n${app}\n})();\n`;
const outputs = new Map([['site.js',runtime],['version.json',JSON.stringify({version:release})+'\n']]);
const pages = ['index','schedule','calculator','records','stats','guide','privacy','settings','notes'].map(name=>name+'.html');
for(const name of pages){
  let html=await read(name);
  html=html.replace(/^\s*<script defer src="\.\/vendor\/quill\.js(?:\?[^\"]*)?"><\/script>\r?\n/gm,'');
  html=html.replace(/((?:src|href)="\.\/(?:site\.js|style\.css|brand\.css|vendor\/quill\.core\.css))(?:\?[^\"]*)?"/g,`$1?v=${release}"`);
  if(html.includes('name="freeter-release"'))html=html.replace(/(<meta name="freeter-release" content=")[^\"]*/,`$1${release}`);
  else html=html.replace('  <meta name="application-name"',`  <meta name="freeter-release" content="${release}">\n  <meta name="application-name"`);
  outputs.set(name,html);
}
const assets = ['./',...pages.map(name=>'./'+name),...['style.css','brand.css','vendor/quill.core.css','site.js'].map(name=>`./${name}?v=${release}`),'./icon.svg','./manifest.webmanifest','./assets/freeter-display.woff2','./assets/freeter-192.png','./assets/freeter-512.png','./assets/gomssi.png'];
outputs.set('sw.js',source['scripts/sw-template.js'].replaceAll('__FREETER_RELEASE__',release).replace('__FREETER_ASSETS__',JSON.stringify(assets)));
for(const [name,value]of outputs){
  if(process.argv.includes('--check')){if(await read(name)!==value)throw new Error(`${name} is stale. Run node scripts/build-site.mjs.`);}
  else await writeFile(new URL(name,root),value);
}
console.log(`${process.argv.includes('--check')?'Verified':'Generated'} self-contained runtime and versioned shell (${release}).`);
